"""Summarize results/*.json into SUMMARY.md (tables) — no recomputation, reads only."""
import json, glob, os
import numpy as np

D = os.path.dirname(os.path.abspath(__file__))
W = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(D, 'results', '*.json')))]
POL = ['P0_const', 'P1_cosine', 'P2_wsd', 'P3_grid', 'P4_model', 'P4v_model_validated', 'OPT_world']
lines = []
P = lines.append


def fmt(x):
    return 'nan' if x is None or (isinstance(x, float) and np.isnan(x)) else ('%.2f' % x)


P('# Goal-2 prototype results (auto-generated by summarize.py)\n')
P('s = (L_base - L_sub) / (L_base - L_opt); L_base = best constant LR (2% warmup), L_opt = our optimizer in the TRUE world.')
P('s is **not capped** at 1: a submission better than our optimizer scores > 1. Divergence scores are raw (very negative).\n')
for kind in 'FCL':
    ws = [w for w in W if w['kind'] == kind]
    P(f'## World kind {kind}  (n_worlds={len(ws)})\n')
    P('| policy | runs | median s@T | min s@T | catastrophic@T (s<-1) | median s@2T | min s@2T | catastrophic@2T | median s_sib@T | gate flags@T |')
    P('|---|---|---|---|---|---|---|---|---|---|')
    for pol in POL:
        rs = [r for w in ws for r in w['results'][pol]]
        sT = [r['T']['s'] for r in rs]
        s2 = [r['T2']['s'] for r in rs if 'T2' in r]
        ssib = [r['T']['s_sib'] for r in rs]
        dv = sum(x < -1 for x in sT)
        dv2 = sum(x < -1 for x in s2)
        fl = sum(r['T']['flag'] for r in rs)
        P(f"| {pol} | {len(rs)} | {fmt(np.median(sT))} | {fmt(min(sT))} | {dv} | {fmt(np.median(s2)) if s2 else '-'} | {fmt(min(s2)) if s2 else '-'} | {dv2} | {fmt(np.median(ssib))} | {fl} |")
    P('')
    P('Per-world detail (s@T; P3/P4/P4v list the two lab seeds):\n')
    P('| world | gap (nats) | P1 | P2 | P3 | P4 | P4v | P4v pilots diverged | opt eta@[.25,.5,.75,.9,1]T |')
    P('|---|---|---|---|---|---|---|---|---|')
    for w in ws:
        g = w['anchors']['10000']['gap']
        cell = lambda pol: ' / '.join(fmt(r['T']['s']) for r in w['results'][pol])
        pil = ' / '.join(str([p['diverged'] for p in r['info'].get('pilots', [])]) for r in w['results']['P4v_model_validated'])
        P(f"| {kind}{w['seed']} | {g:.3f} | {cell('P1_cosine')} | {cell('P2_wsd')} | {cell('P3_grid')} | {cell('P4_model')} | {cell('P4v_model_validated')} | {pil} | {[round(x, 2) for x in w['anchors']['10000']['opt_eta_at']]} |")
    P('')

P('## Ensemble gate: sibling (momentum law) fidelity on the validated monotone domain\n')
P('| world | lam | eps | fit rmse | held-out |dL|/gap median | held-out max |')
P('|---|---|---|---|---|---|')
for w in W:
    s = w['sibling']
    P(f"| {w['kind']}{w['seed']} | {s['lam']} | {s['eps']} | {s['fit_rmse']:.4f} | {s['heldout_disagree_over_gap_median']:.3f} | {s['heldout_disagree_over_gap_max']:.3f} |")
P('')
P('## Red team: sawtooth on top of the world optimum\n')
P('| world | best (a,P) | s (primary MPL) | L - L0 | s_sib | flagged | smallest-amplitude exploit with s>1.05 and L>=L0: (a,P,s,s_sib,flag) |')
P('|---|---|---|---|---|---|---|')
for w in W:
    r = w['results']['P5_redteam_sawtooth'][0]
    ok = [x for x in w['sawtooth_sweep'] if x['s'] > 1.05 and x['L_minus_L0'] >= 0]
    ok.sort(key=lambda x: (x['a'], -x['P']))
    sm = ok[0] if ok else None
    smt = f"({sm['a']},{sm['P']},{sm['s']:.2f},{sm['s_sib']:.2f},{sm['flag']})" if sm else 'none'
    P(f"| {w['kind']}{w['seed']} | ({r['info']['a']},{r['info']['P']}) | {r['T']['s']:.1f} | {r['T']['L'] - w['consts']['L0']:.2f} | {r['T']['s_sib']:.2f} | {r['T']['flag']} | {smt} |")
P('')
nexp = sum(1 for w in W for x in w['sawtooth_sweep'] if x['s'] > 1.05 and x['L_minus_L0'] >= 0)
ncaught = sum(1 for w in W for x in w['sawtooth_sweep'] if x['s'] > 1.05 and x['L_minus_L0'] >= 0 and x['flag'])
P(f'Physically plausible exploits (s>1.05, L>=L0) across all sweeps: {nexp}; flagged by the sibling gate: {ncaught}.\n')
# pessimistic-ensemble scoring: s_pess = min(s, s_sib) always (credit only what every admissible law agrees on)
sp_exp = sum(1 for w in W for x in w['sawtooth_sweep'] if min(x['s'], x['s_sib']) > 1.05)
sp_max = max(min(x['s'], x['s_sib']) for w in W for x in w['sawtooth_sweep'])
P(f'Pessimistic scoring s_pess=min(s,s_sib): sweep entries with s_pess>1.05: {sp_exp}; max s_pess over all sweeps: {sp_max:.3f}.\n')
P('Cost of pessimistic scoring for honest (monotone) policies, median / max of (s - s_pess) at T, over non-catastrophic runs (s > -1;'
  ' catastrophic runs include divergence under some grading jitters, where both laws just return L_div):\n')
for pol in ('P1_cosine', 'P2_wsd', 'P3_grid', 'P4_model', 'P4v_model_validated'):
    d = [r['T']['s'] - min(r['T']['s'], r['T']['s_sib']) for w in W for r in w['results'][pol] if r['T']['s'] > -1]
    P(f'- {pol}: median {np.median(d):.3f}, max {max(d):.3f} (n={len(d)})')
P('')
P('## Planted builder bug (|drop|) — F worlds\n')
for w in W:
    if 'bug_demo' in w:
        b = w['bug_demo']
        P(f"- F{w['seed']}: sibling fitted on the buggy world identical to clean = {b['sibling_same_as_clean']}; red-team s={b['score']['s']:.0f}, s_sib={b['score']['s_sib']:.2f}, flagged={b['score']['flag']}, unphysical={b['score']['unphysical']}")
P('')
# ---------------------------------------------------------------- follow-up (run2.py)
W2 = {(w['kind'], w['seed']): w for w in (json.load(open(f)) for f in sorted(glob.glob(os.path.join(D, 'results2', '*.json'))))}
if W2:
    P('## Follow-up (run2.py): P4m mis-specified family, P6 late-edge probe, OPT_strong\n')
    P(f"anchor reproduction error (max over worlds): {max(w['anchor_repro_err'] for w in W2.values()):.1e}\n")
    P('| kind | P4 s@T (from run.py) | P4m s@T median [min,max] | P6 s@T median [min,max] | P6 s@2T median [min,max] | P6 diverged@T/2T | P6 budget used (max) | OPT_strong - 1 (max) |')
    P('|---|---|---|---|---|---|---|---|')
    for kind in 'FCL':
        ks = [w for (k, s), w in W2.items() if k == kind]
        p4 = [r['T']['s'] for w in W if w['kind'] == kind for r in w['results']['P4_model']]
        m = [r['T']['s'] for w in ks for r in w['results']['P4m_misspecified_family']]
        p6 = [r['T']['s'] for w in ks for r in w['results']['P6_late_edge_probe']]
        p62 = [r['T2']['s'] for w in ks for r in w['results']['P6_late_edge_probe']]
        dv = sum(r['T']['diverged'] is not None for w in ks for r in w['results']['P6_late_edge_probe'])
        dv2 = sum(r['T2']['diverged'] is not None for w in ks for r in w['results']['P6_late_edge_probe'])
        used = max(r['info']['used'] for w in ks for r in w['results']['P6_late_edge_probe'])
        st = max(w['results']['OPT_strong'][0]['T']['s'] - 1 for w in ks)
        rng = lambda v: f'{np.median(v):.2f} [{min(v):.2f},{max(v):.2f}]'
        P(f'| {kind} | {rng(p4)} | {rng(m)} | {rng(p6)} | {rng(p62)} | {dv}/{dv2} | {used} | {st:.4f} |')
    P('')
    P('P6 edge-vs-time estimates in L worlds (true tc, psi vs estimated):\n')
    for (k, s), w in sorted(W2.items()):
        if k == 'L':
            est = '; '.join(f"tc_hat={r['info']['tc_hat']:.0f}, psi_hat={r['info']['psi_hat']:.2f}" if r['info']['tc_hat'] else 'no decay detected'
                            for r in w['results']['P6_late_edge_probe'])
            P(f"- L{s}: true tc={w['true_tc']:.0f}, psi={w['true_psi']:.2f} | {est}")
    fp = [(k, s) for (k, s), w in W2.items() if k != 'L' for r in w['results']['P6_late_edge_probe'] if r['info']['tc_hat']]
    P(f'\nP6 false decay detections in F/C worlds: {len(fp)} {fp}')
open(os.path.join(D, 'SUMMARY.md'), 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines))
