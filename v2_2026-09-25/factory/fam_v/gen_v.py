"""Family V generator: falsification / witness construction over a data-preparation stack.

Gates
  G1 every falsifiable claim has a reference witness the verifier confirms  (existence proof)
  G2 every claim recorded as holding survives a fuzzer                      (no wrong key entries)
  G3 the hard claim is not reachable by random search                       (construction is required)
  G4 degenerate and out-of-scope witnesses are rejected                     (no loophole witnesses)
  G5 the degenerate blanket answers fail                                    (no base-rate shortcut)
"""
