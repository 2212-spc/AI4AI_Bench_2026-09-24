"""Family C generator: 'what can this fleet log actually answer?'

Pipeline stages
  1. build the world and the historical assignment policy (world.py) and materialise the log
  2. compute truth analytically from the structural model; derive per-query tolerances
  3. gate: the blind reference procedure must recover every verdict and every estimate
  4. gate: every alternative-but-valid procedure must also pass  (no false rejection of competence)
  5. gate: every flawed procedure must fail  (mechanical no-shortcut certificate)
  6. gate: both verdict classes well represented, blind guess rate below 1e-3
  7. export the harbor task
"""
