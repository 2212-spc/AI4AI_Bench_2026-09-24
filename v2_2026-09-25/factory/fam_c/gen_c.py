INSTR = """# What can this log actually answer?

`/app/log.csv` is the launch-and-outcome log of 6000 completed training runs of one recipe on a shared
cluster. `/app/columns.md` documents every column, including *when* each one was measured.

Platform engineering wants 12 numbers before the next deployment. Each is in `/app/queries.json`:

```json
{{"id": "q04", "knob": "grad_accum", "from": 1, "to": 2, "baseline": {{...all 10 settings...}}}}
```

Read it as this counterfactual contrast:

> if every job in the fleet were launched with the `baseline` settings but `knob = from`, and then instead
> with the `baseline` settings but `knob = to`, by how much would the mean `val_loss` change?

The mean is over the cluster's own hardware mix and over run-to-run noise; `delta = mean(to) - mean(from)`,
so a negative delta means `to` is better.

**Some of these 12 contrasts cannot be recovered from this log at all.** Part of the job is deciding
which, and saying why. Do not guess a number for a contrast the data cannot support, and do not refuse a
contrast the data can support - both cost you the task.

## Deliverable

`/app/answers.json`, one entry per query id:

```json
{{
  "q01": {{"verdict": "identified", "delta": -0.0123}},
  "q05": {{"verdict": "underdetermined", "reason": "aliased_with_other_knob"}}
}}
```

* `verdict`: `"identified"` if the log determines the contrast, `"underdetermined"` if it does not.
* `delta`: required for `identified`. Correct if within 15% of the true value, or within 0.0025
  absolute, whichever is the larger margin.
* `reason`: required for `underdetermined`, exactly one of
  * `aliased_with_other_knob` - this knob never moved on its own; its effect is inseparable from another
    column's, at any sample size.
  * `level_never_observed` - a value the query asks about never appears in the log.
  * `combination_never_observed` - every value appears somewhere, but the particular combination the
    query needs is absent, so the contrast rests on an assumption the log cannot check.

Also write `/app/audit.md`: for each query, the estimator or the obstruction you found, in a few lines.

## Rules

* Offline task: `/app/log.csv`, `/app/columns.md`, `/app/queries.json` are all the evidence there is.
  There is no simulator and no way to launch a new run.
* Python 3 with numpy is available. Any method is allowed; only the numbers are graded.
* Grading is all-or-nothing over the 12 queries: every verdict, every required delta and every required
  reason has to be right.
"""

README = """# {slug}

Generated by the heterogeneous task factory, family **C** (evidence sufficiency audit), instance seed
`{seed}`.

## Difficulty
The log was produced by a historical assignment policy that plants five distinct obstructions at once:
an unrecorded hardware generation that drives both the operator's choice of `micro_bs` / `seq_len` and
`val_loss`; two knobs that were always flipped together; a value that only ever occurred inside one
stratum and interacts with it; a level that never occurred; and two during-run measurements that sit on
the causal path and therefore must *not* be adjusted for. Answering all 12 queries requires the agent to
(a) pick a correct adjustment set from column *timing* rather than column *usefulness*, (b) model effect
modification, because every query is asked at a specific baseline, and (c) abstain exactly three or four
times, for the right reason. Grading is all-or-nothing, so being right about ten of twelve scores zero.
Blind verdict guessing succeeds with probability {chance:.2e}.

## Reference solution
`solution/ref_solve.py` is a blind analyst: it reads only the files the agent gets, encodes every launch
setting categorically, saturates all pairwise interactions between launch settings, adjusts for the
pre-flight hardware probe, adjusts for nothing measured during the run, and answers a query only when the
requested contrast is estimable from the observed design. Estimates land at {max_rel:.1%} of tolerance in
the worst case.

## Verification
`tests/verify_c.py` compares the submitted verdicts, deltas and reasons against `tests/truth.json`, which
was computed analytically from the structural model, not from any fit. The verifier runs no agent code.
`authoring/certificate.json` records the gates: the reference procedure and {n_alt} alternative-but-valid
procedure(s) pass; all {n_cand} flawed procedures fail, each with the query that catches it.
"""


def gates(rows, qs, truth):
    def score(ans):
        bad = []
        for q in qs:
            i = q["id"]; t = truth[i]; a = ans.get(i, {})
            if a.get("verdict") != t["verdict"]:
                bad.append({"q": i, "why": "verdict", "got": a.get("verdict")}); continue
            if t["verdict"] == "identified":
                d = a.get("delta")
                if d is None or abs(d - t["delta"]) > t["tol"]:
                    bad.append({"q": i, "why": "delta", "got": None if d is None else round(d, 5)})
        return bad
    ref = E.answer(rows, qs, E.REF)
    ref_bad = score(ref)
    rel = max((abs(ref[q["id"]]["delta"] - truth[q["id"]]["delta"]) / truth[q["id"]]["tol"])
              for q in qs if truth[q["id"]]["verdict"] == "identified")
    alt = {n: score(E.answer(rows, qs, o)) for n, o in E.ALTERNATIVES.items()}
    cand = {n: score(E.answer(rows, qs, o)) for n, o in E.CANDIDATES.items()}
    return ref, {
        "n_rows": len(rows), "n_queries": len(qs),
        "verdict_mix": {v: sum(1 for t in truth.values() if t["verdict"] == v)
                        for v in ("identified", "underdetermined")},
        "G_reference_passes": not ref_bad, "reference_failures": ref_bad,
        "G_reference_margin_worst_frac_of_tol": round(rel, 3),
        "G_alternatives_pass": all(not v for v in alt.values()),
        "alternatives": {k: (v[:2] or "pass") for k, v in alt.items()},
        "G_all_flawed_procedures_fail": all(bool(v) for v in cand.values()),
        "flawed_procedures_caught_by": {k: (v[0]["q"] + ":" + v[0]["why"] if v else "SURVIVED")
                                        for k, v in cand.items()},
        "G_both_classes_present": all(sum(1 for t in truth.values() if t["verdict"] == v) >= 3
                                      for v in ("identified", "underdetermined")),
        "G_blind_guess_rate": 2.0 ** (-len(qs)),
    }, rel


def main():
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 20260924
    out = sys.argv[2] if len(sys.argv) > 2 else "/tmp/bench2/tasks/c-audit-a"
    slug = os.path.basename(out)
    rows = world.sample_log(N_ROWS, seed)
    qs = world.queries()
    truth = {}
    for q in qs:
        d = world.true_delta(q["knob"], q["from"], q["to"], q["baseline"])
        t = {"delta": round(d, 6), "tol": round(max(0.15 * abs(d), 0.0025), 6)}
        if q["id"] in UNDET:
            t.update(verdict="underdetermined", reasons_ok=UNDET[q["id"]])
        else:
            t.update(verdict="identified", reasons_ok=[])
        truth[q["id"]] = t
    ref, cert, rel = gates(rows, qs, truth)
    cert["accepted"] = bool(cert["G_reference_passes"] and cert["G_alternatives_pass"]
                            and cert["G_all_flawed_procedures_fail"] and cert["G_both_classes_present"])
    print(json.dumps(cert, indent=1)[:4000])
    if not cert["accepted"]:
        print("REJECTED"); return 1

    # ---- export -------------------------------------------------------------------------------
    buf = io.StringIO()
    wcsv = csv.writer(buf)
